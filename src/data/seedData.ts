export function evaluateDateSensitiveRules(transactionDate: string, bankCategory: BankCategory) {
  const txTime = transactionDate ? new Date(transactionDate).getTime() : NaN;
  const cutoff2027 = new Date('2027-01-01').getTime();
  const isPost2027 = !Number.isNaN(txTime) && txTime >= cutoff2027;
  const isCommercialBank = bankCategory === 'Commercial Bank';

  const applicableLiabilityRule =
    isPost2027 && isCommercialBank
      ? {
          sourceId: 'SRC-RBI-2026-RBC',
          title: 'RBI Commercial Banks – Responsible Business Conduct Third Amendment Directions, 2026',
          reason:
            'Transaction date is on or after 1 January 2027 and entity is a Commercial Bank; 2026 Amendment Directions apply (including 5-calendar-day third-party breach rule and 45/60-day resolution limits).',
        }
      : {
          sourceId: 'SRC-RBI-2017-ULL',
          title: 'RBI Circular on Limiting Liability of Customers in Unauthorised Electronic Banking Transactions (July 2017)',
          reason: isPost2027
            ? `Bank category (${bankCategory}) is outside the Commercial Banks 2026 Amendment Directions; check entity-specific RBI circular.`
            : 'Transaction occurred prior to 1 January 2027. The 2026 Third Amendment Directions expressly commence on 1 January 2027 and must NOT be applied retroactively.',
        };

  const ombudsmanCoveredCategories: BankCategory[] = [
    'Commercial Bank',
    'Regional Rural Bank',
    'Cooperative Bank',
    'Qualifying NBFC',
    'Non-Bank PPI Issuer',
    'Credit Information Company',
  ];

  const isCoveredEntity = ombudsmanCoveredCategories.includes(bankCategory);

  return {
    applicableLiabilityRule,
    ombudsmanScheme: {
      sourceId: 'SRC-RBI-2026-IOS',
      title: 'Reserve Bank – Integrated Ombudsman Scheme, 2026 (Effective 1 July 2026)',
      isCoveredEntity,
      note: isCoveredEntity
        ? `${bankCategory} falls within covered entity categories, subject to threshold conditions in the Scheme.`
        : 'Entity may fall outside RBI Integrated Ombudsman Scheme, 2026 coverage.',
    },
  };
}

export function evaluateOmbudsmanEligibility(params: {
  bankCategory: BankCategory;
  complaintDate?: string;
  bankResponse?: string;
  bankResponseDate?: string;
  hasWrittenProof: boolean;
  pendingInCourt: boolean;
  commercialJudgmentOnly: boolean;
  referenceDate?: string;
}): OmbudsmanEligibilityCheck {
  const refDate = params.referenceDate ? new Date(params.referenceDate) : new Date('2026-11-20');
  const coveredTypes: BankCategory[] = [
    'Commercial Bank',
    'Regional Rural Bank',
    'Cooperative Bank',
    'Qualifying NBFC',
    'Non-Bank PPI Issuer',
    'Credit Information Company',
  ];
  const entityCovered = coveredTypes.includes(params.bankCategory);

  let step2: OmbudsmanEligibilityCheck['step2ResponsePeriodResult'] = 'Unclear';
  let within90Days = true;
  let daysSinceComplaint = 0;

  if (params.complaintDate) {
    const cmpDate = new Date(params.complaintDate);
    daysSinceComplaint = Math.floor((refDate.getTime() - cmpDate.getTime()) / (1000 * 60 * 60 * 24));
    if (params.bankResponse && params.bankResponse.trim().length > 0) {
      step2 = 'Dissatisfied with reply';
      if (params.bankResponseDate) {
        const respDate = new Date(params.bankResponseDate);
        const daysSinceResp = Math.floor((refDate.getTime() - respDate.getTime()) / (1000 * 60 * 60 * 24));
        within90Days = daysSinceResp <= 90;
      }
    } else if (daysSinceComplaint >= 30) {
      step2 = 'Passed 30 days';
      within90Days = daysSinceComplaint - 30 <= 90;
    } else {
      step2 = 'Pending (<30 days)';
    }
  }

  const flags: string[] = [];
  if (!params.hasWrittenProof) flags.push('No prior written complaint or proof of submission to the regulated entity.');
  if (!params.complaintDate) flags.push('Incomplete complaint timeline: date of complaint to bank is missing.');
  if (step2 === 'Pending (<30 days)') {
    flags.push(`30-day bank response period has not expired (${daysSinceComplaint} days elapsed since complaint) and no final reply is recorded.`);
  }
  if (!within90Days) flags.push('Complaint may exceed the 90-day filing window from expiry of response period or last bank communication.');
  if (!entityCovered) flags.push('Entity category may not be covered under the RBI Integrated Ombudsman Scheme, 2026.');
  if (params.pendingInCourt) flags.push('Same grievance is reported as pending before or decided by a court, tribunal, arbitrator, or other forum.');
  if (params.commercialJudgmentOnly) flags.push('Matters involving purely commercial judgment or services outside RBI regulatory purview may be non-maintainable.');

  let preliminaryResult: OmbudsmanEligibilityCheck['preliminaryResult'] = 'Potentially Eligible (Subject to RBI Scrutiny)';
  if (!params.hasWrittenProof || !entityCovered || params.pendingInCourt || params.commercialJudgmentOnly || !within90Days) {
    preliminaryResult = 'Maintainability / Coverage Concerns Flagged';
  } else if (step2 === 'Pending (<30 days)' || step2 === 'Unclear') {
    preliminaryResult = 'Premature — Wait for Bank Response Window';
  }

  return {
    checkedAt: refDate.toISOString().slice(0, 10),
    ruleVersion: 'Reserve Bank – Integrated Ombudsman Scheme, 2026 (Effective 1 July 2026)',
    step1ApproachedBank: params.hasWrittenProof,
    step2ResponsePeriodResult: step2,
    step3WithinTimeLimit: within90Days,
    step4EntityCovered: entityCovered,
    step5MaintainabilityFlags: flags,
    preliminaryResult,
    rationale:
      flags.length === 0
        ? 'Preliminary procedural checks appear satisfied under the 2026 Scheme (prior bank complaint recorded, 30-day or reply condition met, within 90-day window, covered entity, no flagged exclusions). Final maintainability rests solely with the RBI Ombudsman.'
        : 'One or more procedural, coverage, or maintainability flags require attention before filing on RBI CMS. This automated check is informational and not a binding determination.',
  };
}

